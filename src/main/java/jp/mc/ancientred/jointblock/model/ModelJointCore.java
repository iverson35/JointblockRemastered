   public void setAdditionalRenderState(IJBJointParameterHolder joint, float partial) {
      float rate;
      if (!(joint instanceof TileEntityJointCore)) {
         rate = 1.0F;
      } else {
         TileEntityJointCore te = (TileEntityJointCore)joint;
         rate = te.openFrontPrev + (te.openFront - te.openFrontPrev) * partial;
      }

      this.PadBoxTZN.rotateAngleX = 90.0F * rate / 57.295776F;
      this.PadBoxBZN.rotateAngleX = -90.0F * rate / 57.295776F;
      this.PadBoxV3.rotateAngleY = (90.0F - 90.0F * rate) / 57.295776F;
      this.PadBoxV4.rotateAngleY = (-180.0F + 90.0F * rate) / 57.295776F;
      this.OpenUR1.rotationPointY = 11.0F + -4.0F * rate;
      this.OpenUR2.rotationPointY = 11.0F + -3.0F * rate;
      this.OpenUR3.rotationPointY = 11.0F + -2.0F * rate;
      this.OpenUR4.rotationPointY = 11.0F + -1.0F * rate;
      this.OpenUR5.rotationPointY = 11.0F + -0.0F * rate;
      this.OpenBL1.rotationPointY = 21.0F + 4.0F * rate;
      this.OpenBL2.rotationPointY = 21.0F + 3.0F * rate;
      this.OpenBL3.rotationPointY = 21.0F + 2.0F * rate;
      this.OpenBL4.rotationPointY = 21.0F + 1.0F * rate;
      this.OpenBL5.rotationPointY = 21.0F + 0.0F * rate;
      this.OpenBR1.rotationPointX = 5.0F + 4.0F * rate;
      this.OpenBR2.rotationPointX = 5.0F + 3.0F * rate;
      this.OpenBR3.rotationPointX = 5.0F + 2.0F * rate;
      this.OpenBR4.rotationPointX = 5.0F + 1.0F * rate;
      this.OpenBR5.rotationPointX = 5.0F + 0.0F * rate;
      this.OpenUL1.rotationPointX = -5.0F - 4.0F * rate;
      this.OpenUL2.rotationPointX = -5.0F - 3.0F * rate;
      this.OpenUL3.rotationPointX = -5.0F - 2.0F * rate;
      this.OpenUL4.rotationPointX = -5.0F - 1.0F * rate;
      this.OpenUL5.rotationPointX = -5.0F - 0.0F * rate;
   }

   private void setRotation(JBModelRenderer model, float x, float y, float z) {
      model.rotateAngleX = x;
      model.rotateAngleY = y;
      model.rotateAngleZ = z;
   }
